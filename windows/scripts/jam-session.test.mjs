test('end of file self-advance: the player already on the Jam\'s new track is not reloaded', async () => {
  const jam = await bootJam();
  await jam.start();
  await jam.time.advance(500);
  // The native queue advances by itself to the next row (EOF) before the Jam reports it.
  jam.app.player.currentIndex = 1;
  jam.app.player.base = 0; jam.app.player.at = jam.time.now();
  jam.jam.onPlaybackState(jam.app.state());
  const plays = jam.app.callsOf('play_song').length;
  await jam.push({track: track(2), queue: [track(3)], positionMs: 0});
  await jam.time.advance(1000);
  assert.equal(jam.app.callsOf('play_song').length, plays);
  assert.equal(jam.view.current.uri, 'spotify:track:2');
  assert.equal(jam.app.player.items[jam.app.player.currentIndex].videoId, 'yt-2');
  // Native ids are regenerated by every replacement: the new upcoming list still lands and sync keeps the player.
  await jam.time.advance(6000);
  jam.jam.onPlaybackState(jam.app.state());
  assert.equal(jam.app.callsOf('play_song').length, plays);
  assert.deepEqual(jam.app.player.items.slice(jam.app.player.currentIndex).map(item => item.videoId), ['yt-2', 'yt-3']);
  assert.equal(jam.app.player.playing, true);
  assert.equal(jam.app.callsOf('pause_playback').length, 0);
  assert.equal(jam.view.sync.status, 'locked');
});

