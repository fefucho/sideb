test('a failed search is retried with backoff and never cached as unavailable', async () => {
  let failures = 2;
  const jam = await bootJam({app: {search: query => {
    if (failures > 0) { failures -= 1; throw {code: 'SEARCH_FAILED', message: 'network'}; }
    return [catalog(/Title (\w+)/.exec(query)[1])];
  }}});
  await jam.start({state: {queue: []}});
  assert.notEqual(jam.view.current.status, 'unavailable');
  assert.equal(jam.app.callsOf('play_song').length, 0);
  await jam.time.advance(2100);   // first retry (2 s) fails again
  assert.notEqual(jam.view.current.status, 'unavailable');
  assert.equal(jam.app.callsOf('play_song').length, 0);
  await jam.time.advance(5100);   // second retry (5 s) succeeds
  assert.equal(jam.view.current.status, 'matched');
  assert.equal(jam.app.callsOf('play_song').length, 1);
  assert.equal(jam.app.callsOf('search_songs').length, 3);
});

