test('jam_replace_upcoming failing (queue taken over) is tolerated: no crash, no loop', async () => {
  const jam = await bootJam();
  await jam.start();
  await jam.time.advance(500);
  jam.app.player.source = {kind: 'album', id: 'x', title: 'x'};
  jam.jam.onPlaybackState(jam.app.state());
  await jam.push({track: track(1), queue: [track(3)]});
  await jam.time.advance(5000);
  assert.equal(jam.app.callsOf('jam_replace_upcoming').length, 0, 'not called when the queue is not a Jam queue');
  jam.app.player.source = {kind: 'jam', id: null, title: 'Spotify Jam'};
  let calls = 0;
  jam.app.on('jam_replace_upcoming', () => { calls += 1; throw {code: 'JAM_QUEUE_NOT_ACTIVE', message: 'x'}; });
  jam.jam.onPlaybackState(jam.app.state());
  await jam.push({track: track(1), queue: [track(2)]});
  await jam.time.advance(10_000);
  assert.ok(calls >= 1 && calls <= 2, `calls ${calls}`);
  assert.equal(jam.view.phase, 'active');
});

